def run_ref_init(live, force, game="chess"):
    """Initialize match state in `live` by shelling out to the deployed
    referee script (ref.py for chess, ref_xq.py for xiangqi, ref_cw.py for
    corewar), always passing ARCADE_LIVE explicitly in the subprocess
    environment.

    Every engine script deployed into a live dir — the referee included —
    now resolves `D = Path(os.environ.get('ARCADE_LIVE', '/tmp/<game>'))` at
    import time instead of hardcoding a default live dir, so setting
    ARCADE_LIVE on the subprocess (rather than relying on it being inherited
    from our own environment, which it may not be) reaches any live dir, not
    just the default. This used to be a live hazard: a copy of ref.py shelled
    into from a scratch live dir would silently reinitialize the real
    /tmp/chess instead, which is what wiped a live game's moves.txt/fen.txt
    during a previous hardening round (design-history.md §10) — that vector
    is closed now that the engine itself honors ARCADE_LIVE.
    """
    ref_script = GAME_REF_SCRIPT.get(game, "ref.py")
    with_args = []
    for pkg in GAME_UV_WITH.get(game, []):
        with_args += ["--with", pkg]
    cmd = ["uv", "run", "--quiet", *with_args, "python", str(live / ref_script), "init"]
    if force:
        cmd.append("--force")
    env = {**os.environ, "ARCADE_LIVE": str(live)}
    subprocess.run(cmd, cwd=live, env=env, check=True)


# Every file PER_MATCH_TRUNCATE/PER_MATCH_UNLINK is about to clear belongs
# here too -- snapshot_pre_start's docstring says "every non-empty file",
# not "every evidence-worthy file"; that is ARCHIVE_FILES's job, a narrower
# and separate list. menu.txt has no archival value (see ARCHIVE_FILES's
# comment) but is cheap to snapshot and the invariant is meant to be
# unconditional, so it is included here anyway.
SNAPSHOT_FILES = ["moves.txt", "fen.txt", "chat.log", "banner.txt", "results.txt",
                   "names.txt", "seats.txt", "eval.log", "keeper.log", "result.txt",
                   "stage_log.txt", "menu.txt"]


def snapshot_pre_start(live, newest):
    """Copy every non-empty file `start` is about to overwrite or clear into
    <live>/backup/<name>.<tag>.<ext>. Returns the backup dir, or None if
    there was nothing to save.

    The gate is per file, not "moves.txt is non-empty": a finished match with
    an empty moves.txt but a non-empty chat.log must still snapshot the chat
    log, now that reset_room() truncates it. Snapshot failure is fatal —
    refusing to start beats clearing without a copy.
    """
    tag = f"match-{newest[1]['match']:03d}" if newest else str(int(time.time()))
    backup_dir = None
    for fn in SNAPSHOT_FILES:
        src = live / fn
        try:
            if not (src.exists() and src.read_text().strip()):
                continue
        except OSError as e:
            print(f"error: could not read {src} to snapshot it before start: {e}", file=sys.stderr)
            sys.exit(1)
        if backup_dir is None:
            backup_dir = live / "backup"
            backup_dir.mkdir(parents=True, exist_ok=True)
        stem, dot, ext = fn.partition(".")
        dest = backup_dir / f"{stem}.{tag}.{ext}" if dot else backup_dir / f"{fn}.{tag}"
        try:
            shutil.copy2(src, dest)
        except OSError as e:
            print(f"error: failed to snapshot {src} to {dest}: {e}", file=sys.stderr)
            sys.exit(1)
    return backup_dir


def reset_room(live):
    """Clear per-match social/broadcast/runtime state. Call ONLY after a
    successful ref init and only after snapshot_pre_start has run.

    Truncate-vs-unlink is deliberate: chat.log/banner.txt/eval.log/
    keeper.log/ctl are tailed by running panes, so they are emptied in place,
    never unlinked. The ref-owned flag files are unlinked because their
    *existence* is the signal.
    """
    for fn in PER_MATCH_TRUNCATE:
        p = live / fn
        if p.exists():
            p.write_text("")
    for fn in PER_MATCH_UNLINK:
        (live / fn).unlink(missing_ok=True)
    for pat in PER_MATCH_GLOBS:
        for p in live.glob(pat):
            if p.is_file():
                p.unlink(missing_ok=True)


def cmd_start(args):
    root = get_root(args)
    live = get_live_dir(args)
    engine = root / "engine"
    games_dir = games_dir_for(root, args.game)

    game_default_live = default_live_for(args.game)
    if live != game_default_live:
        # Historically this warned that the override wouldn't hold at all
        # (design-history.md §10) — engine scripts hardcoded /tmp/chess and
        # ignored env/cwd. Fixed: every engine script now reads ARCADE_LIVE
        # at import time, and run_ref_init passes it explicitly to the
        # referee's subprocess. The remaining gap is scripts run by hand
        # later (e.g. a seated agent's shell) — those only follow `live` if
        # ARCADE_LIVE is set in *their* environment too.
        print(f"note: live dir is {live}, not {game_default_live} — this init run honors it. "
              f"If you run any deployed engine script by hand afterward, export "
              f"ARCADE_LIVE={live} first so it resolves the same dir.", file=sys.stderr)
    elif os.environ.get("ARCADE_ROOT") and not live_dir_explicit(args):
        # Incident-driven: ARCADE_ROOT overrides the games root to a scratch
        # tree, but the live dir silently defaulted to the real /tmp/chess —
        # this is exactly the vector that wiped a live game's moves.txt/fen.txt
        # during verification. Always a mistake; no --force override.
        print(f"refusing: ARCADE_ROOT={os.environ['ARCADE_ROOT']} overrides the games root to "
              f"{root}, but no --live-dir/ARCADE_LIVE was given so the live dir defaulted to "
              f"{game_default_live} (production) — scratch games root with production live dir. "
              f"Pass --live-dir or set ARCADE_LIVE.", file=sys.stderr)
        sys.exit(1)

    # Deploy preflight (before step 4): every file the deploy loop (step 5)
    # copies must exist under engine/ BEFORE start makes any filesystem
    # change. Without this a missing engine file surfaces as a copy2
    # traceback AFTER match_dir was created, orphaning a match.json-less
    # match dir that hard-blocks every later `arcade start` ("already
    # exists (stale or corrupt match dir?)") — same trap class as the
    # seat-validation path step 6 cleans up after.
    deploy_files = GAME_DEPLOY_FILES.get(args.game, DEPLOY_FILES)
    missing = [fn for fn in deploy_files if not (engine / fn).is_file()]
    if missing:
        print(f"error: cannot start {args.game}: engine dir {engine} is missing "
              f"{len(missing)} deploy file(s): {', '.join(missing)} — refusing; "
              f"no match dir was created.", file=sys.stderr)
        sys.exit(1)

    games_dir.mkdir(parents=True, exist_ok=True)

    # The guard is about the newest match dir's status, not moves.txt content:
    # archive() flips status to complete but never touches the live dir, so a
    # non-empty moves.txt left over from a *finished* match is normal, not a
    # game in progress. Only a still-"live" newest match blocks a fresh start.
    newest = find_newest_match(games_dir)
    if newest and newest[1].get("status") == "live" and not args.force:
        d, _ = newest
        print(f"refusing: {d.name} is still live — pass --force to override.", file=sys.stderr)
        sys.exit(1)
    # Either the newest match is complete/abandoned (its log is legitimately
    # finished) or there's no prior match at all — either way ref.py init
    # doesn't need the *operator* to have passed --force to proceed cleanly.
    force_init = True

    # Concurrent `arcade start` invocations racing on next_match_number()/mkdir
    # is a known gap — single-operator tool, not guarded against here.
    num = next_match_number(games_dir)
    match_dir = games_dir / f"{MATCH_RE_PREFIX}{num:03d}"
    try:
        match_dir.mkdir(parents=True)
    except FileExistsError:
        print(f"error: {match_dir} already exists (stale or corrupt match dir?) — "
              f"resolve it by hand before retrying.", file=sys.stderr)
        sys.exit(1)

    live.mkdir(parents=True, exist_ok=True)
    for fn in deploy_files:
        shutil.copy2(engine / fn, live / fn)

    # Step 6: build + validate seats before any identity/room mutation, so a
    # bad seat name fails loudly instead of clearing state on the way out.
    # match_dir (step 4) and the deployed engine files (step 5) already
    # exist at this point -- validate_seats's sys.exit(1) would otherwise
    # leave a match.json-less match_dir behind that hard-blocks every later
    # `arcade start` ("already exists"), so clean it up on this path too,
    # mirroring the failed-ref-init cleanup below.
    seats = {"white": seat(args.white), "black": seat(args.black)}
    try:
        validate_seats(seats)
    except SystemExit:
        shutil.rmtree(match_dir, ignore_errors=True)
        raise
    W, B = seats["white"]["name"], seats["black"]["name"]

    # Step 7: unarchived-match warning. Not a refusal — an operator who
    # forgets `arcade archive` should still be able to seat the next match;
    # the snapshot (step 8) is what makes that safe.
    if newest and not (newest[0] / "chat.log").exists() and (live / "chat.log").exists():
        print(f"note: {newest[0].name} was never archived (no chat.log in its match dir). "
              f"The live room is being reset for the new match; its contents are "
              f"snapshotted to {live}/backup/. Run `arcade archive` first next time.",
              file=sys.stderr)

    # Step 8: snapshot everything the reset below is about to overwrite/clear.
    backup_dir = snapshot_pre_start(live, newest)

    # Step 9: identity files, written fresh every start — must precede init
    # because render() reads names.txt (after the §7 identity-leak fix).
    (live / "names.txt").write_text(f"{W} {B}\n")
    # seats.txt is the seat-bound identity contract game_cli.py/game_xq_cli.py
    # (via chat.require_seated()) hard-refuse submit/resign/offer-draw/accept-draw
    # against: `<NAME> white` / `<NAME> black`, one line each. Game-5 retro fix --
    # a wrong/unset identity used to stage silently and get discarded later.
    (live / "seats.txt").write_text(f"{W} white\n{B} black\n")

    try:
        run_ref_init(live, force_init, game=args.game)
    except subprocess.CalledProcessError as e:
        shutil.rmtree(match_dir, ignore_errors=True)
        print(f"error: match init failed (exit {e.returncode}) — no match dir was created. "
              f"See any output above for why.", file=sys.stderr)
        sys.exit(e.returncode or 1)

    # Step 11: clear per-match social/broadcast/runtime state, now that init
    # has succeeded. --keep-room skips this (re-seating an interrupted match,
    # or dev iteration) but not the snapshot above.
    if not getattr(args, 'keep_room', False):
        reset_room(live)

    # roles.txt removes the stale-role leak: chat.roles() overrides role_of(),
    # so a leftover line from a departed player would misclassify the new
    # seats. Written fresh every start (regardless of --keep-room), always
    # AFTER reset_room: roles.txt is also in PER_MATCH_UNLINK (its *absence*
    # doubles as the reset signal for an older deployed engine build that
    # still reads it that way), so writing it before the reset would just
    # have it deleted again.
    (live / "roles.txt").write_text(
        f"{W} white\n{B} black\nARCADE facilitator\nREFEREE facilitator\n"
        f"DIRECTOR facilitator\nHOST facilitator\n")

    # host.txt is the herdr agent name game.sh/game_xq.sh auto-poke after a
    # staging verb succeeds (2e rename: was director.txt — see
    # docs/design-history.md §14; game.sh/game_xq.sh fall back to a stale
    # director.txt from an older deploy if host.txt is absent). Same
    # lifecycle as roles.txt: in PER_MATCH_UNLINK (so a hostless start clears
    # a stale one via reset_room above) and rewritten fresh here, after the
    # reset, when a host is seated this match.
    if args.host:
        (live / "host.txt").write_text(args.host.lower() + "\n")

    # Step 12: series.txt + seeded banner.txt + seeded chat.log, all
    # pairing-filtered against the cumulative results.txt ledger.
    rows = parse_results(read_text(live / "results.txt"))
    rec = head_to_head(rows, W, B)
    wa, wb, _dr, n = rec
    short = series_short(W, B, rec)
    (live / "series.txt").write_text(short + "\n")

    c1, c2 = color_labels(args.game)
    tag = "FIRST MEETING" if not n else f"{W} {wa}-{wb} {B}"
    (live / "banner.txt").write_text(f"GAME {num} — {W} vs {B} — {tag}\n")

    if not getattr(args, 'keep_room', False):
        line = (f"match-{num:03d} opens: {W} ({c1.title()}) vs {B} ({c2.title()}). "
                f"Fresh room — the previous match's chat is archived. "
                f"Series, this pairing: {short}.")
        (live / "chat.log").write_text(f"{int(time.time())}\tARCADE\t{line}\n")

    # match.json is only written once init has actually succeeded, so a failed
    # start never leaves an orphaned match dir behind.
    data = {
        "game": args.game,
        "match": num,
        "started": datetime.now().isoformat(timespec="seconds"),
        "seats": seats,
        "host": host_seat(args.host) if args.host else None,
        "live_dir": str(live),
        "status": "live",
        "result": None,
        "ended": None,
    }
    write_match_json(match_dir, data)

    print_runbook(data, live, backup_dir)


