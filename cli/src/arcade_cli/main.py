def find_arcade_root(start):
    """Nearest ancestor of `start` that looks like an arcade checkout.

    An arcade root holds both `engine/` (the runtime the CLI deploys) and
    `cli/` (this package's own project dir). Both are required so a stray
    `engine/` elsewhere on the path cannot be mistaken for the root.
    """
    for cand in (start, *start.parents):
        if (cand / "engine").is_dir() and (cand / "cli").is_dir():
            return cand
    return None


def default_root():
    """Where games/ and engine/ live, when no --root and no ARCADE_ROOT.

    Resolution order, so a fresh clone works with no configuration:
      1. $ARCADE_ROOT
      2. the arcade checkout containing this file (an editable/uv-run install
         keeps main.py inside the tree, which is the normal case)
      3. the arcade checkout containing $PWD (a non-editable `uv tool install`
         copies the package out of the tree, so the cwd is the only clue)
      4. $PWD, which then fails loudly on a missing engine/ rather than
         silently pointing at one particular machine's home directory
    """
    env = os.environ.get("ARCADE_ROOT")
    if env:
        return Path(env)
    here = Path(__file__).resolve()
    found = find_arcade_root(here.parent)
    if found:
        return found
    cwd = Path.cwd().resolve()
    return find_arcade_root(cwd) or cwd


def get_root(args):
    return Path(args.root) if getattr(args, "root", None) else default_root()


