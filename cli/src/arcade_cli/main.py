# series (results.txt is cumulative and pairing-agnostic; every display of it
# must be filtered through head_to_head for the pairing actually on screen)

VALID_SCORES = ("1-0", "0-1", "1/2-1/2")


def parse_results(text):
    """[(white, score, black)] from `<WHITE> <SCORE> <BLACK>` lines; skips junk."""
    rows = []
    for ln in text.splitlines():
        p = ln.split()
        if len(p) == 3 and p[1] in VALID_SCORES:
            rows.append((p[0].upper(), p[1], p[2].upper()))
    return rows


def head_to_head(rows, a, b):
    """(wins_a, wins_b, draws, games) for the {a,b} pairing, order-insensitive:
    a line counts whichever colour each player held."""
    a, b = a.upper(), b.upper()
    wa = wb = dr = 0
    for white, score, black in rows:
        if {white, black} != {a, b}:
            continue
        if score == "1/2-1/2":
            dr += 1
        elif (score == "1-0") == (white == a):
            wa += 1
        else:
            wb += 1
    return wa, wb, dr, wa + wb + dr


def series_short(a, b, rec):
    wa, wb, dr, n = rec
    if not n:
        return "FIRST MEETING"
    tail = f", {dr} draw(s)" if dr else ""
    return f"{a} {wa}-{wb} {b} ({n} game(s){tail})"


