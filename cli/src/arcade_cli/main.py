# CLI wiring

def build_parser():
    # `--live-dir` needs to work both before and after the subcommand name
    # (`arcade --live-dir X status` and `arcade status --live-dir X`). A
    # subparser replaces the whole namespace with a fresh one on its own
    # defaults and then copies it onto the parent — so if the subparser's
    # copy also defaults live_dir to None, it silently clobbers a value set
    # at the top level. default=SUPPRESS keeps the attribute out of that
    # fresh namespace when the flag wasn't given at the subcommand level, so
    # the top-level value (if any) survives instead of being overwritten.
    live_dir_help = "live runtime dir (default: $ARCADE_LIVE or /tmp/chess)"

    p = argparse.ArgumentParser(prog="arcade", description="Match manager for the AI Agent Arcade.")
    p.add_argument("--live-dir", help=live_dir_help)
    sub = p.add_subparsers(dest="command", required=True)

    s = sub.add_parser("start", help="allocate + deploy a new match")
    s.add_argument("--live-dir", help=live_dir_help, default=argparse.SUPPRESS)
    s.add_argument("game")
    # --red is an alias for --white (same dest): both name the first-mover
    # seat -- chess calls it white, xiangqi and corewar call it red, but
    # internally (match.json, host_prompt, print_runbook) it's the same
    # "white" key throughout, matching ref_xq.py's own white<->red seat
    # mapping. Either spelling works for any game (main() warns, doesn't
    # refuse, if the off-game spelling is used -- see the seat-flag mismatch
    # note in warn_seat_flag_mismatch).
    s.add_argument("--white", "--red", dest="white", required=True,
                    help="first-mover seat: chess calls this --white, xiangqi/corewar call it "
                         "--red (same flag; either spelling is accepted for any game)")
    # --blue is an alias for --black (same dest, same pattern as
    # --white/--red above): corewar's second seat is "blue", internally the
    # same "black" key everywhere.
    s.add_argument("--black", "--blue", dest="black", required=True,
                    help="second seat: chess/xiangqi call this --black, corewar calls it --blue "
                         "(same flag; either spelling is accepted for any game)")
    # --director is the pre-2e-rename spelling, kept working forever (same
    # dest pattern as --white/--red above): the seat is HOST everywhere
    # forward-looking now (docs/design-history.md §14), --host is what the
    # runbook and docs show, but a caller/script still using --director must
    # not break.
    s.add_argument("--host", "--director", dest="host",
                    help="booth/host seat's herdr agent; --director is a back-compat alias")
    s.add_argument("--force", action="store_true")
    s.add_argument("--keep-room", action="store_true", dest="keep_room",
                    help="skip clearing chat.log/eval.log/keeper.log/ctl (identity files, "
                         "series.txt and banner.txt are still rewritten); does not skip the "
                         "pre-start snapshot")
    s.set_defaults(func=cmd_start)

    st = sub.add_parser("status", help="show live match status")
    st.add_argument("--live-dir", help=live_dir_help, default=argparse.SUPPRESS)
    st.add_argument("--game", default="chess")
    st.set_defaults(func=cmd_status)

    a = sub.add_parser("archive", help="archive the live match into its match dir")
    a.add_argument("--live-dir", help=live_dir_help, default=argparse.SUPPRESS)
    a.add_argument("--game")
    a.add_argument("--result")
    a.set_defaults(func=cmd_archive)

    r = sub.add_parser("results", help="series table across all matches")
    r.add_argument("--pairing", nargs=2, metavar=("A", "B"),
                    help="restrict the match listing and head-to-head block to this "
                         "pairing (order-insensitive, case-insensitive) and suppress "
                         "the all-time line")
    r.set_defaults(func=cmd_results)

    pr = sub.add_parser("prompt", help="print prompts")
    pr_sub = pr.add_subparsers(dest="prompt_command", required=True)
    # "director" is kept as an alias (2e rename, same back-compat spirit as
    # --host/--director above) so an existing `arcade prompt director` caller
    # keeps working; "host" is the name docs/runbooks show going forward.
    prd = pr_sub.add_parser("host", aliases=["director"], help="print the host seating prompt")
    prd.add_argument("--game", default="chess")
    prd.set_defaults(func=cmd_prompt_host)

    return p


def warn_seat_flag_mismatch(args, argv):
    """--white/--red share one dest and --black/--blue share another (see
    build_parser) so `arcade start chess --red kimi` parses silently -- cheap
    enough to just note the off-game spelling was used and move on, not worth
    a hard refusal over. Conventional spellings per game: GAME_SEAT_FLAGS."""
    if getattr(args, "command", None) != "start":
        return
    tokens = sys.argv[1:] if argv is None else argv
    first, second = GAME_SEAT_FLAGS.get(args.game, ("--white", "--black"))
    if "--red" in tokens and first != "--red":
        print(f"note: --red is xiangqi/corewar's spelling of the first-mover seat flag; "
              f"game is {args.game!r} — accepted anyway, but {first} is conventional here.",
              file=sys.stderr)
    elif "--white" in tokens and first != "--white":
        print(f"note: --white works for {args.game} too (same seat), but {first} is the "
              f"conventional spelling for this game.", file=sys.stderr)
    if "--blue" in tokens and second != "--blue":
        print(f"note: --blue is corewar's spelling of the second seat flag; "
              f"game is {args.game!r} — accepted anyway, but {second} is conventional here.",
              file=sys.stderr)
    elif "--black" in tokens and second != "--black":
        print(f"note: --black works for {args.game} too (same seat), but {second} is the "
              f"conventional spelling for this game.", file=sys.stderr)


def main(argv=None):
    parser = build_parser()
    args = parser.parse_args(argv)
    warn_seat_flag_mismatch(args, argv)
    args.func(args)


if __name__ == "__main__":
    main()
