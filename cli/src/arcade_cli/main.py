def seat(agent):
    lowered = agent.lower()
    if lowered == "human" or lowered.startswith("human:"):
        name = agent[len("human:"):] if lowered.startswith("human:") else ""
        if not name:
            print("error: --white/--black human requires a name, e.g. human:ada", file=sys.stderr)
            sys.exit(1)
        if any(c.isspace() for c in name):
            print(f"error: human seat name {name!r} must not contain whitespace "
                  f"(names.txt is space-separated) — use human:adalovelace, not human:ada lovelace",
                  file=sys.stderr)
            sys.exit(1)
        return {"agent": "human", "name": name.upper()}
    return {"agent": agent, "name": agent.upper()}


def validate_seats(seats):
    """Two cheap refusals the reset/seeding scaffolding now depends on:
    identical names make seats.txt/roles.txt/role_of()/head_to_head() all
    ambiguous, and a reserved name would be misclassified by roles.txt (or
    could not be seat-checked at all)."""
    white_name, black_name = seats["white"]["name"], seats["black"]["name"]
    if white_name == black_name:
        print(f"error: white and black seat names are both {white_name!r} — "
              f"names must be distinct.", file=sys.stderr)
        sys.exit(1)
    for name in (white_name, black_name):
        if name in RESERVED_NAMES:
            print(f"error: {name!r} is a reserved name ({sorted(RESERVED_NAMES)}) — "
                  f"pick a different seat name.", file=sys.stderr)
            sys.exit(1)


def host_seat(agent):
    # CHESS_NAME=HOST is the fixed convention (FACILITATOR.md) — the room
    # always sees "HOST", regardless of which agent holds the seat. (2e
    # rename: this was DIRECTOR/"DIRECTOR" — see docs/design-history.md §14.
    # DIRECTOR stays reserved in RESERVED_NAMES for old archives.)
    return {"agent": agent, "name": "HOST"}


def host_prompt(data, live):
    white, black = data["seats"]["white"], data["seats"]["black"]
    # `data.get("host")` covers matches seated after the 2e rename;
    # `data.get("director")` is the fallback for older match.json files
    # written under the pre-rename schema (see docs/design-history.md §14).
    host = data.get("host") or data.get("director")
    game = data["game"]
    c1, c2 = color_labels(game)
    facilitator = GAME_FACILITATOR.get(game, "FACILITATOR.md")
    lines = []
    if host:
        lines.append(f"export CHESS_NAME={host['name']}")
    lines.append(f"cd {live}")
    lines.append(f"Read {live}/{facilitator} and follow it exactly.")
    lines.append(
        f"You are hosting match {data['match']} ({game}): "
        f"{white['name']} ({c1}, agent {white['agent']}) vs "
        f"{black['name']} ({c2}, agent {black['agent']})."
    )
    return "\n".join(lines)


def human_runbook(seat_data, color, live, script="game.sh"):
    name = seat_data["name"]
    lines = [
        f"# You are {name} ({color}). Play with:",
        f"export CHESS_NAME={name}",
        f"bash {live}/{script} show",
        f"bash {live}/{script} submit '<move>'",
        f"bash {live}/{script} say '<message>'",
        f"bash {live}/{script} status       # one-shot recovery: ply/turn/last move/pending",
        f"bash {live}/{script} history      # numbered move list",
        f"bash {live}/{script} await-turn   # block until it's your move, then show",
    ]
    return "\n".join(lines)


