def cmd_status(args):
    root = get_root(args)
    live = get_live_dir(args)
    games_dir = games_dir_for(root, args.game)

    moves = read_text(live / "moves.txt").split()
    ply = len(moves)
    side = "white" if ply % 2 == 0 else "black"
    last_san = moves[-1] if moves else None
    fen = read_text(live / "fen.txt").strip() or None
    pending_raw = read_text(live / "pending.txt").strip()
    if pending_raw and "\t" in pending_raw:
        who, san = pending_raw.split("\t", 1)
        pending = f"{san} (staged by {who})"
    else:
        pending = pending_raw or None
    names = read_text(live / "names.txt").split()

    match = find_newest_match(games_dir, status="live") or find_newest_match(games_dir)
    results_text = read_text(live / "results.txt")
    results_lines = [l for l in results_text.splitlines() if l.strip()]

    print(f"live dir: {live}")
    if match:
        d, data = match
        print(f"match: {d.name} ({data['status']}) — {data['seats']['white']['name']} vs "
              f"{data['seats']['black']['name']}")
    else:
        print("match: (no match.json found)")
    print(f"ply: {ply}  to move: {side}")
    print(f"last move: {last_san or '(none)'}")
    print(f"fen: {fen or '(missing)'}")
    print(f"pending: {pending or '(none staged)'}")
    if names:
        print(f"names.txt: {' '.join(names)}")

    # series is always pairing-filtered — printing the last raw results.txt
    # line here is exactly the reported bug (it names the *previous*
    # pairing). Pairing comes from the resolved match's match.json seats,
    # falling back to names.txt when no match.json was found.
    if match:
        pw = match[1]["seats"]["white"]["name"]
        pb = match[1]["seats"]["black"]["name"]
    elif len(names) == 2:
        pw, pb = names[0], names[1]
    else:
        pw = pb = None
    if pw and pb:
        rec = head_to_head(parse_results(results_text), pw, pb)
        print(f"series ({pw} vs {pb}): {series_short(pw, pb, rec)}   "
              f"[results.txt: {len(results_lines)} line(s) total]")
    else:
        print("series: (no pairing known)")


