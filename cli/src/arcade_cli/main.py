def cmd_results(args):
    root = get_root(args)
    games_root = root / "games"
    if not games_root.exists():
        print("no games directory found")
        return

    pairing = None
    if getattr(args, "pairing", None):
        pairing = {args.pairing[0].upper(), args.pairing[1].upper()}

    for game_dir in sorted(p for p in games_root.iterdir() if p.is_dir()):
        matches = list(iter_matches(game_dir))
        if pairing:
            matches = [(d, data) for d, data in matches
                       if {data["seats"]["white"]["name"], data["seats"]["black"]["name"]} == pairing]
        if not matches:
            continue
        print(f"== {game_dir.name} ==")
        tally, draws, pending = {}, 0, 0
        # Per-pairing grouping is the default (not opt-in): with rotating
        # players an ungrouped "series" number is meaningless. Key by
        # frozenset({white, black}) so colour doesn't split a pairing in two.
        by_pairing = {}
        for d, data in matches:
            white = data["seats"]["white"]["name"]
            black = data["seats"]["black"]["name"]
            result = data.get("result") or "(pending)"
            print(f"  {d.name}  {white} vs {black}  [{data['status']}]  {result}")
            r = data.get("result") or ""
            score = r.split()[1] if len(r.split()) > 1 else ""
            by_pairing.setdefault(frozenset((white, black)), []).append((white, score, black))
            if score == "1-0":
                tally[white] = tally.get(white, 0) + 1
            elif score == "0-1":
                tally[black] = tally.get(black, 0) + 1
            elif score == "1/2-1/2":
                draws += 1
            else:
                pending += 1

        if by_pairing:
            print("  head-to-head:")
            def sort_key(item):
                key, rows = item
                decided = sum(1 for _, s, _ in rows if s in VALID_SCORES)
                return (-decided, sorted(key))
            for key, rows in sorted(by_pairing.items(), key=sort_key):
                a, b = sorted(key)
                decided_rows = [(w, s, bl) for w, s, bl in rows if s in VALID_SCORES]
                pending_n = len(rows) - len(decided_rows)
                summary = series_short(a, b, head_to_head(decided_rows, a, b))
                if pending_n:
                    summary += f" ({pending_n} pending)"
                print(f"    {a} vs {b}:  {summary}")

        # Per-pairing grouping replaces the ungrouped all-time line when a
        # --pairing filter is active — with one pairing on screen the
        # head-to-head block above already says everything the all-time
        # line would.
        if not pairing and (tally or draws or pending):
            series = "  ".join(f"{name} {wins}" for name, wins in sorted(tally.items(), key=lambda kv: -kv[1]))
            extra = []
            if draws:
                extra.append(f"{draws} draw(s)")
            if pending:
                extra.append(f"{pending} pending/undecided")
            tail = ("  " + "  ".join(extra)) if extra else ""
            print(f"  all-time: {series}{tail}")


