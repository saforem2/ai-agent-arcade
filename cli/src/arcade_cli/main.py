# match.json helpers

def match_number(match_dir):
    try:
        return int(match_dir.name[len(MATCH_RE_PREFIX):])
    except ValueError:
        return None


def iter_matches(games_dir):
    """Yield (match_dir, data) for every match-NNN dir, sorted by number.

    A dir that looks like a match (matches the naming pattern) but has no
    readable match.json is skipped — loudly, since silently skipping it would
    let next_match_number() reuse its number and crash on mkdir later.
    """
    if not games_dir.exists():
        return
    dirs = [d for d in games_dir.iterdir() if d.is_dir() and d.name.startswith(MATCH_RE_PREFIX)]
    for d in sorted(dirs, key=lambda d: match_number(d) or 0):
        mj = d / "match.json"
        if not mj.exists():
            print(f"warning: {d} has no match.json — skipping, its number may be reused", file=sys.stderr)
            continue
        try:
            yield d, json.loads(mj.read_text())
        except json.JSONDecodeError as e:
            print(f"warning: {mj} is not valid JSON ({e}) — skipping, its number may be reused", file=sys.stderr)
            continue


def next_match_number(games_dir):
    nums = [match_number(d) for d, _ in iter_matches(games_dir)]
    nums = [n for n in nums if n is not None]
    return (max(nums) if nums else 0) + 1


def find_newest_match(games_dir, status=None):
    """Newest (highest-numbered) match dir, optionally filtered by status."""
    best = None
    for d, data in iter_matches(games_dir):
        if status is not None and data.get("status") != status:
            continue
        best = (d, data)
    return best


def resolved_live_dir(path):
    """Return a stable absolute spelling for live-dir identity checks."""
    try:
        return Path(path).expanduser().resolve()
    except (TypeError, OSError, RuntimeError):
        return None


def match_uses_live_dir(data, live):
    """Whether a match record is bound to the requested live directory."""
    recorded_live = resolved_live_dir(data.get("live_dir"))
    return recorded_live is not None and recorded_live == resolved_live_dir(live)


def find_live_matches_for_dir(root, live):
    """All live matches, across every game, bound to ``live``."""
    games_root = root / "games"
    if not games_root.exists():
        return []

    matches = []
    for games_dir in sorted(p for p in games_root.iterdir() if p.is_dir()):
        for match_dir, data in iter_matches(games_dir):
            if data.get("status") == "live" and match_uses_live_dir(data, live):
                matches.append((games_dir.name, match_dir, data))
    return matches


def write_match_json(match_dir, data):
    (match_dir / "match.json").write_text(json.dumps(data, indent=2) + "\n")


