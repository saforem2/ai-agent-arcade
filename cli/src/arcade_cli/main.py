def cmd_archive(args):
    root = get_root(args)
    live = resolved_live_dir(get_live_dir(args))
    game = getattr(args, "game", None)

    if game is None:
        # With no game selector, the live-dir binding is the only safe source
        # of game identity. Never guess from whichever game's match number is
        # newest: that can copy one game's runtime over another game's archive.
        matches = find_live_matches_for_dir(root, live)
        if not matches:
            print(f"no live match for {live} across {root / 'games'}; "
                  f"pass --game <game> only to re-archive a completed match "
                  f"whose live_dir is {live}", file=sys.stderr)
            sys.exit(1)
        if len(matches) > 1:
            found = ", ".join(f"{found_game}/{match_dir.name}"
                              for found_game, match_dir, _ in matches)
            print(f"multiple live matches for {live}: {found}; "
                  f"pass --game <game> to select one", file=sys.stderr)
            sys.exit(1)
        _, match_dir, data = matches[0]
    else:
        games_dir = games_dir_for(root, game)

        # Preserve the explicit-game behavior: prefer the newest live match,
        # then permit an idempotent re-archive of the newest completed match.
        # In both cases, verify the record's live-dir binding before any copy.
        selected = find_newest_match(games_dir, status="live")
        if selected:
            match_dir, data = selected
            if not match_uses_live_dir(data, live):
                recorded_live = resolved_live_dir(data.get("live_dir"))
                other = recorded_live or data.get("live_dir") or "(missing live_dir)"
                print(f"--game {game} selected live match {match_dir.name} for {other}; "
                      f"requested live dir is {live} — refusing cross-game archive.",
                      file=sys.stderr)
                sys.exit(1)
        else:
            selected = find_newest_match(games_dir)
            if not selected:
                print(f"no match found under {games_dir}", file=sys.stderr)
                sys.exit(1)
            match_dir, data = selected
            if not match_uses_live_dir(data, live):
                recorded_live = resolved_live_dir(data.get("live_dir"))
                other = recorded_live or data.get("live_dir") or "(missing live_dir)"
                print(f"no live match for {live}; --game {game}'s newest match belongs "
                      f"to {other} — refusing cross-game archive.", file=sys.stderr)
                sys.exit(1)

    # `game` is None on the inferred path above (the tuple unpack there
    # discards it), so fall back to the match record's own game field.
    archive_game = game or data.get("game")
    for fn in ARCHIVE_FILES + GAME_ARCHIVE_EXTRA.get(archive_game, []):
        src = live / fn
        if src.exists():
            dest = match_dir / fn
            dest.parent.mkdir(parents=True, exist_ok=True)  # nested extras (warriors/...)
            shutil.copy2(src, dest)

    result = args.result
    if not result:
        lines = [l for l in read_text(live / "results.txt").splitlines() if l.strip()]
        result = lines[-1] if lines else None

    data["status"] = "complete"
    data["result"] = result
    data["ended"] = datetime.now().isoformat(timespec="seconds")
    write_match_json(match_dir, data)

    print(f"archived {match_dir.name}: result={result!r}")


